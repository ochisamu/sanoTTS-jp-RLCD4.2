CHARS = ''.join(chr(i) for i in range(0x3041, 0x3097)) + 'ー。、！？0123456789'
VOCAB = ['<pad>', '<bos>', '<sep>', '<eos>', '<unk>'] + list(CHARS)
VOCAB += [f'<unused{i}>' for i in range(128-len(VOCAB))]
IDS = {c:i for i,c in enumerate(VOCAB)}

def normalize(text):
    text = unicodedata.normalize('NFKC', text).translate(str.maketrans({'!':'！','?':'？'}))
    return ''.join(chr(ord(c)-0x60) if 0x30a1 <= ord(c) <= 0x30f6 else c
                   for c in text if not c.isspace())

def encode(text):
    return [IDS.get(c, 4) for c in normalize(text)]

def decode(ids):
    return ''.join(VOCAB[i] for i in ids if 5 <= i < 5+len(CHARS))

def corpus():
    train=[]; valid=[]
    for intent, questions, held, replies in CASES:
        answers=replies.split('|')
        for q in questions.split('|'):
            for prefix in ('', 'ねえ、', 'あのね、'):
                for suffix in ('', '。'):
                    for a in answers:
                        train.append(dict(intent=intent, question=prefix+q+suffix, answer=a))
        for q in held.split('|'):
            valid.append(dict(intent=intent, question=q, answers=answers))
    assert not {e['question'] for e in train} & {e['question'] for e in valid}
    assert all(4 not in encode(e['question']+e['answer']) for e in train)
    return train, valid
