"""Compile original knowledge cards and exact reading/display pairs to Flash C.

Does not need training corpora or model weights. Uses the authored source seeds
and the same host-side reading converter as training.
"""
import json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def main():
    sys.path.insert(0,str(ROOT/'tiny_lm'))
    from dialogue_data import Kana
    from daily_dialogue import CASES as DAILY
    from improvement_data import CASES as EXTRA
    from knowledge_data import CARDS
    from data import CASES as ORIGINAL
    convert=Kana()
    cards=[dict(id=r['id'],aliases=[convert(q) for q in r['questions'].split('|')],
                reading=convert(r['answer']),display=r['answer']) for r in CARDS]
    answers=[r[3] for r in DAILY]+[r[3] for r in EXTRA]+[r['answer'] for r in CARDS]
    answers += [r[3].split('|')[0] for r in ORIGINAL if r[0] not in ('unknown','like')]
    captions={};conflicts=set()
    for a in answers:
        k=convert(a).replace('。','').replace('、','')
        if k in captions and captions[k]!=a:conflicts.add(k)
        captions[k]=a
    for k in conflicts:captions.pop(k)
    def c(s):return json.dumps(s,ensure_ascii=False)
    rows=['/* Generated by prepare_reply_assets.py; original text MIT. */',
          'typedef struct { const char *id,*query,*reading,*display; } kb_row;',
          'static const kb_row reply_knowledge[] = {']
    for card in cards:
        for q in card['aliases']:
            rows.append('{'+','.join(c(v) for v in [card['id'],q,card['reading'],card['display']])+'},')
    rows+=['};','typedef struct { const char *reading,*display; } caption_row;',
           'static const caption_row reply_captions[] = {']
    for k,v in sorted(captions.items()):rows.append('{'+c(k)+','+c(v)+'},')
    rows+=['};','']
    dest=ROOT/'.cache/reply-assets';dest.mkdir(exist_ok=True)
    (dest/'reply_assets.h').write_text('\n'.join(rows))
    (dest/'knowledge.json').write_text(json.dumps(cards,ensure_ascii=False,indent=2)+'\n')
    (dest/'captions.json').write_text(json.dumps(captions,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(dict(cards=len(cards),aliases=sum(len(c['aliases']) for c in cards),captions=len(captions))))
if __name__=='__main__':main()
